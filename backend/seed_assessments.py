async def seed_all():
    total_added = 0
    for slug, items in BANKS.items():
        course = await db.courses.find_one({"slug": slug}, {"_id": 0, "quiz": 1})
        if not course:
            continue
        # Dedupe by question text (case & whitespace normalized) because full-course
        # upserts periodically reset quiz IDs; text is our stable natural key.
        def _norm(t: str) -> str:
            return " ".join((t or "").lower().split())
        existing_texts = {_norm(q.get("question", "")) for q in course.get("quiz", [])}
        candidates = _build(slug, items)
        new_items = [q for q in candidates if _norm(q["question"]) not in existing_texts]
        if not new_items:
            continue
        await db.courses.update_one(
            {"slug": slug},
            {"$push": {"quiz": {"$each": new_items}}},
        )
        total_added += len(new_items)
    logger.info(f"Assessment banks seeded: +{total_added} questions across {len(BANKS)} courses.")
    return total_added
