"""Seed & extend randomized assessment question banks for all 24 courses.

For courses with existing full quizzes (10 full courses), we augment with domain
questions. For catalog-only courses (14), we seed a full bank of 15-18 questions.

Idempotent: uses a stable question_id derived from slug + question hash so we can
upsert without duplicates on re-run.
"""
from __future__ import annotations

import hashlib
from typing import List

from core import db, logger
from models import QuizQuestion


def _qid(slug: str, question_text: str) -> str:
    """Stable ID so re-seeds don't duplicate."""
    h = hashlib.md5(f"{slug}::{question_text}".encode()).hexdigest()[:12]
    return f"q-{slug[:20]}-{h}"


def _build(slug: str, items: List[dict]) -> List[dict]:
    out = []
    for it in items:
        q = QuizQuestion(
            id=_qid(slug, it["question"]),
            question=it["question"],
            type=it.get("type", "mcq"),
            options=it["options"],
            correct=it["correct"],
            explanation=it.get("explanation", ""),
            difficulty=it.get("difficulty", "intermediate"),
        )
        out.append(q.model_dump())
    return out


